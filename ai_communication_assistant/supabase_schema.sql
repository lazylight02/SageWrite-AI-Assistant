-- Run this script in Supabase Dashboard > SQL Editor.

create table if not exists public.generated_messages (
    id bigint generated by default as identity primary key,
    name text not null,
    message_type text not null check (message_type in ('Email', 'LinkedIn')),
    purpose text not null,
    company text not null,
    generated_content text not null,
    created_at timestamptz not null default now()
);

-- Enable Row Level Security (RLS)
alter table public.generated_messages enable row level security;

-- Drop existing policies if they exist to allow clean re-execution
drop policy if exists "Allow app to read generated messages" on public.generated_messages;
drop policy if exists "Allow app to insert generated messages" on public.generated_messages;

-- Policy to allow reading generated messages (for demo/prototype)
create policy "Allow app to read generated messages"
on public.generated_messages for select
to anon, authenticated
using (true);

-- Policy to allow inserting generated messages (for demo/prototype)
create policy "Allow app to insert generated messages"
on public.generated_messages for insert
to anon, authenticated
with check (true);
